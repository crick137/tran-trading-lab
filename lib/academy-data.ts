// ─── Helper functions ────────────────────────────────────────────

export function getModule(moduleId: string): AcademyModule | undefined {
    return academyModules.find((m) => m.id === moduleId);
}

export function getLesson(moduleId: string, lessonSlug: string): { module: AcademyModule; lesson: Lesson; index: number } | undefined {
    const mod = getModule(moduleId);
    if (!mod) return undefined;
    const index = mod.lessons.findIndex((l) => l.slug === lessonSlug);
    if (index === -1) return undefined;
    return { module: mod, lesson: mod.lessons[index], index };
}

export function getAllLessons(): { moduleId: string; moduleTitle: string; lesson: Lesson; index: number }[] {
    return academyModules.flatMap((mod) =>
        mod.lessons.map((lesson, index) => ({
            moduleId: mod.id,
            moduleTitle: mod.title,
            lesson,
            index,
        }))
    );
}
